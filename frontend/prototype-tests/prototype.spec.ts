test('teacher has no live progress, may edit closed instructions, and can download only final mock roster', async ({ page }) => {
  await page.goto(url)
  await page.getByLabel('Preview as').selectOption('teacher')
  await expect(workspace(page)).not.toContainText('Noah Wu')
  await expect(tab(page, 'Requests')).toHaveCount(0)
  await page.getByRole('button', { name: 'Extend deadline' }).click()
  await page.getByLabel('New deadline · America/New_York').fill('2026-10-22T17:00')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('alert')).toContainText('later than')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByLabel('Activity state').selectOption('finalizing')
  await expect(page.getByRole('button', { name: 'Extend deadline' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit instructions' }).click()
  await page.getByLabel('Instructions', { exact: true }).fill('Updated plain-text instructions.')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(workspace(page)).toContainText('Updated plain-text instructions.')
  await tab(page, 'Final roster').click()
  await expect(page.getByRole('button', { name: 'Download CSV' })).toHaveCount(0)
  await page.getByLabel('Activity state').selectOption('finalized')
  await tab(page, 'Final roster').click()
  await expect(page.locator('.roster-row')).toHaveCount(9)
  await page.screenshot({ path: 'test-results/prototype-teacher-roster.png', fullPage: true })
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download CSV' }).click()
  expect((await downloaded).suggestedFilename()).toBe('mock-final-roster.csv')
})

test('conflict and uncertain response never automatically submit an application or replay an action', async ({ page }) => {
  await page.goto(url)
  await page.getByText('Scenarios', { exact: true }).click()
  await page.getByLabel('Interaction simulation').selectOption('conflict')
  await page.getByRole('button', { name: 'Join this group' }).click()
  await page.getByRole('button', { name: 'Confirm joining' }).click()
  await expect(page.getByRole('alert')).toContainText('no longer empty')
  await expect(workspace(page)).toContainText('Find your people.')
  await page.getByLabel('Interaction simulation').selectOption('uncertain')
  await page.getByRole('button', { name: 'Apply to join', exact: true }).last().click()
  await page.getByRole('button', { name: 'Send application' }).click()
  await expect(page.getByRole('alert')).toContainText('No action has been replayed')
})

test('desktop and mobile screens are navigable without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/?prototype=1#courses')
  await expect(page.locator('.course-grid')).toBeVisible()
  await page.screenshot({ path: 'test-results/prototype-courses-desktop.png', fullPage: true })
  await page.locator('.course-card').filter({ hasText: 'Interaction Design' }).click()
  await page.screenshot({ path: 'test-results/prototype-groups-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/prototype-groups-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await tab(page, 'Classmates').click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enter demo workspace' })).toBeVisible()
})
