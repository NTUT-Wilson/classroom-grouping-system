import { expect, test } from '@playwright/test'

const url = '/?prototype=1#course/interaction/groups'
const workspace = (page: import('@playwright/test').Page) => page.locator('.workspace')
const tab = (page: import('@playwright/test').Page, name: string) => page.locator('.course-tabs').getByRole('link', { name, exact: true })

test('student joining works without API traffic and preserves private history', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(request.url()) })
  await page.goto(url)
  await page.getByRole('button', { name: 'Join this group', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Leaving or switching groups is not available')
  await page.getByRole('button', { name: 'Confirm joining' }).click()
  await expect(page.getByRole('heading', { name: 'You belong to Group 3.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Apply to join', exact: true })).toHaveCount(0)
  await tab(page, 'Requests').click()
  await expect(workspace(page)).toContainText('System-canceled')
  await page.getByRole('button', { name: 'Invitations', exact: true }).click()
  await expect(workspace(page)).toContainText('Student joined a group')
  await expect(workspace(page)).toContainText('Rejected')
  expect(apiRequests).toEqual([])
})

test('manager approval fills last place and closes other pending requests', async ({ page }) => {
  await page.goto(url)
  await page.getByLabel('Preview as').selectOption('noah')
  await tab(page, 'Requests').click()
  const ethan = page.locator('.request-row').filter({ hasText: 'Ethan Tsai' })
  await expect(ethan).toBeVisible()
  await page.screenshot({ path: 'test-results/prototype-manager-requests.png', fullPage: true })
  await ethan.getByRole('button', { name: 'Approve', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm membership' }).click()
  await expect(workspace(page)).toContainText('Group full')
  await expect(workspace(page)).toContainText('Accepted')
  await expect(page.getByRole('button', { name: 'Approve', exact: true })).toHaveCount(0)
  await page.getByLabel('Preview as').selectOption('alex')
  await tab(page, 'Requests').click()
  await expect(workspace(page)).toContainText('Group full')
})

test('teacher setup validates capacity and opens activity only after confirmation', async ({ page }) => {
  await page.goto('/?prototype=1#courses')
  await page.getByLabel('Preview as').selectOption('teacher')
  await page.locator('.course-card').filter({ hasText: 'Visual Communication' }).click()
  await expect(page.getByRole('button', { name: 'Review activity' })).toBeVisible()
  await page.screenshot({ path: 'test-results/prototype-teacher-setup.png', fullPage: true })
  await page.getByLabel('Group capacities', { exact: true }).fill('2, 2')
  await page.getByRole('button', { name: 'Review activity' }).click()
  await expect(page.getByRole('alert')).toContainText('totaling exactly 9')
  await page.getByLabel('Group capacities', { exact: true }).fill('2, 2, 2, 3')
  await page.getByRole('button', { name: 'Review activity' }).click()
  await expect(page.getByRole('dialog')).toContainText('immediately visible')
  await expect(page.locator('.page-heading')).toContainText('No activity yet')
  await page.getByRole('button', { name: 'Create activity', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Activity created')
  await expect(workspace(page)).toContainText('Fixed capacity layout')
  await expect(page.getByLabel('Group capacities', { exact: true })).toHaveCount(0)
  await expect(workspace(page)).not.toContainText('Alex Chen')
  await page.getByLabel('Preview as').selectOption('alex')
  await expect(page.locator('.group-card')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Join this group', exact: true })).toHaveCount(4)
})

