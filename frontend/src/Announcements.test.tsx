  await user.click(trigger)
  expect(screen.getByRole('dialog', { name: 'Delete announcement?' })).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Cancel deletion' }))
  expect(trigger).toHaveFocus(); expect(api.sendAnnouncementCommand).not.toHaveBeenCalled()
  await user.click(trigger)
  await act(async () => { screen.getByRole('dialog').dispatchEvent(new Event('cancel', { bubbles: true, cancelable: true })) })
  expect(api.sendAnnouncementCommand).not.toHaveBeenCalled()
  await user.click(trigger)
  vi.mocked(api.getAnnouncement).mockRejectedValue(new api.ApiError(404, 'deleted'))
  await user.click(screen.getByRole('button', { name: 'Confirm deletion' }))
  expect(await screen.findByRole('status')).toHaveTextContent('Announcement deleted.')
  expect(api.sendAnnouncementCommand).toHaveBeenCalledWith(course.id, { command: 'DELETE', commandKey: expect.any(String), id: notice.id, expectedRevision: 1 })
